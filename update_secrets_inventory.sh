#!/usr/bin/env bash
set -euo pipefail

# Parses the compose files and writes every secret they use to secrets.inventory.
# Add a service with ${MY_APP_PASSWORD:?...} and this script records it; no list to edit.
# setup_homelab.sh and the pre-commit hook run it for you.

# shellcheck source=lib/secrets-common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/secrets-common.sh"

show_usage() {
    cat <<EOF
Usage: $0 [--check]

Writes every secret used by the compose project to secrets.inventory.

Options:
    --check     Do not write; fail if secrets.inventory is out of date (for CI)
    -h, --help  Show this help
EOF
}

check_only=false
case "${1:-}" in
    "") ;;
    --check) check_only=true ;;
    -h | --help) show_usage; exit 0 ;;
    *) show_usage; die "Unknown option: $1" ;;
esac

# Prints the inventory file: a header, then one aligned "SERVICE VARIABLE KIND" line per secret
render_inventory() {
    local services service name kind
    mapfile -t services < <(compose_services all)

    echo "# Secrets used by the compose project. Generated by ./update_secrets_inventory.sh;"
    echo "# do not edit by hand. KIND is required (\${VAR:?...}) or optional."
    printf '%-24s %-40s %s\n' "# SERVICE" VARIABLE KIND
    compose_secrets "${services[@]}" | sort | while read -r service name kind; do
        printf '%-24s %-40s %s\n' "$service" "$name" "$kind"
    done
}

# Prints the variable names in an inventory, one per line, without duplicates
variable_names() {
    awk '!/^#/ && NF { print $2 }' | sort -u
}

new=$(render_inventory)
old=$(cat "$INVENTORY_FILE" 2>/dev/null || true)

if [[ "$new" == "$old" ]]; then
    log_info "secrets.inventory is up to date"
    exit 0
fi

if $check_only; then
    diff <(echo "$old") <(echo "$new") >&2 || true
    die "secrets.inventory is out of date. Run ./update_secrets_inventory.sh and commit the result."
fi

added=$(comm -13 <(variable_names <<< "$old") <(variable_names <<< "$new") | tr '\n' ' ')
removed=$(comm -23 <(variable_names <<< "$old") <(variable_names <<< "$new") | tr '\n' ' ')
echo "$new" > "$INVENTORY_FILE"

log_info "Updated secrets.inventory"
[[ -z "$added" ]] || log_info "New secrets: $added(run ./setup_homelab.sh to store them)"
[[ -z "$removed" ]] || log_info "No longer used: $removed(you can delete them from your password manager)"
