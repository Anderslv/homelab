# shellcheck shell=bash
# Renders the generated .env.example from lib/map.sh's rows, and parses it back.
# It exists so the file's format lives in one place: descriptions, then a
# "# (kind · sensitivity · services)" line, then a bare VAR= that copies as empty.

# OLD_FILE: prints the new .env.example, keeping the descriptions in OLD_FILE.
render_env_example() {
  local rows
  map_ready
  rows=$(map_rows) || return 1
  MAP_ROWS_TSV=$rows MAP_STACKS_TSV=$MAP_STACKS awk '
    # "# ── TEXT ───…" padded to 78 columns (at least "──"); · and ─ are one column each.
    function header(text,   line, plain) {
      line = "# ── " text " ─"; plain = line; gsub(/·|─/, ".", plain)
      do { line = line "─"; plain = plain "." } while (length(plain) < 78)
      return line
    }
    # OLD_FILE: the "# " lines directly above each VAR=, without headers and the
    # "# (…)" metadata line.
    /^# \(.*\)$/ { next }
    /^# / && !/^# ── / { block = block $0 "\n"; next }
    /^[A-Za-z_][A-Za-z0-9_]*=/ { name = $0; sub(/=.*/, "", name); known[name] = 1; desc[name] = block }
    { block = "" }
    END {
      n = split(ENVIRON["MAP_STACKS_TSV"], lines, "\n")
      for (i = 1; i <= n; i++) { split(lines[i], f, "\t"); file[f[1]] = f[2]; profiles[f[1]] = f[3] }
      print "# Every variable the compose files use, generated by scripts/secrets/map.sh."
      print "# Edit only the description lines above a variable. Never put values here."
      n = split(ENVIRON["MAP_ROWS_TSV"], rows, "\n")
      for (i = 1; i <= n; i++) {
        split(rows[i], f, "\t")   # section var kind default sensitivity services message
        if (f[1] != section) {
          section = f[1]; text = section " · used across the project"
          if (section != "core") text = section " · " file[section]
          if (profiles[section] != "") text = text " · profiles: " profiles[section]
          print ""; print header(text)
        }
        if (f[2] in known) printf "%s", desc[f[2]]
        else print "# " (f[7] != "" ? f[7] : "TODO: describe")
        used = split(f[6], list, " ")
        print "# (" f[3] (f[3] == "default" ? " " f[4] : "") " · " f[5] " · " (used > 3 ? used " services" : f[6]) ")"
        print f[2] "="
      }
    }' "$1"
}

# FILE: parses a generated .env.example into TSV section, var, kind, default,
# sensitivity, description (the description lines joined by spaces).
example_rows() {
  awk '
    /^# ── / { section = $0; sub(/^# ── /, "", section); sub(/ .*/, "", section); desc = ""; next }
    /^# \(.*\)$/ { meta = substr($0, 4, length($0) - 4); next }
    /^# / { desc = desc (desc == "" ? "" : " ") substr($0, 3); next }
    /^[A-Za-z_][A-Za-z0-9_]*=/ {
      name = $0; sub(/=.*/, "", name); split(meta, field, " · ")
      kind = field[1]; value = ""
      if (kind ~ /^default /) { value = substr(kind, 9); kind = "default" }
      printf "%s\t%s\t%s\t%s\t%s\t%s\n", section, name, kind, value, field[2], desc
    }
    { desc = ""; meta = "" }' "$1"
}
